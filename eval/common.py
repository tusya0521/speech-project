"""Small helpers shared by the eval scripts."""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
RESULTS = os.path.join(ROOT, "eval", "results")
SAMPLE_DOC = os.path.join(ROOT, "eval", "sample_doc", "speech_recognition_notes.pdf")
TAG = os.getenv("RESULT_TAG", "")  # e.g. "with-key" -> qa_text_with-key.md


def out(name: str) -> str:
    """Path in eval/results for a result file, with RESULT_TAG appended before the extension."""
    base, ext = os.path.splitext(name)
    return os.path.join(RESULTS, f"{base}_{TAG}{ext}" if TAG else name)


SYNTHETIC_BANNER ="> **SYNTHETIC - not a result.** Audio was generated by TTS for script testing only.\n\n"


def write_csv(path: str, rows: list[dict]):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def md_table(rows: list[dict]) -> str:
    cols = list(rows[0].keys())
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join(lines) + "\n"


def environment() -> str:
    """One line describing where the numbers were measured (goes into every results file)."""
    import platform
    from voicetutor import asr, config
    try:
        gpu = asr.local_device()
    except Exception:
        gpu = "unknown"
    return (f"Measured on {platform.node()} ({platform.system()}, Python {platform.python_version()}, "
            f"local ASR device {gpu}, Groq key {'set' if config.GROQ_API_KEY else 'not set'}, "
            f"local model {config.LOCAL_WHISPER_MODEL}).\n\n")
